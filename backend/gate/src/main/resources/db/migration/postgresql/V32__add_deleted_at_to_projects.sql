-- UG-303: 프로젝트를 삭제해도 생체 특징점과 이미지가 그대로 남는다.
--
-- 소프트 삭제(is_deleted = true)만 하고 그 프로젝트에 등록된 얼굴·손바닥 특징점과 MinIO 에
-- 올라간 원본 이미지는 손대지 않는다. 조회 경로가 전부 막혀 접근은 안 되지만 데이터는 남는다.
-- "프로젝트를 지웠다" 는 사용자 입장에서 그 데이터가 없어졌다는 뜻으로 읽히고, 저장소는
-- 회수 경로 없이 쌓이며, 온프레미스에서는 "이 프로젝트 데이터를 지워 달라" 가 수작업이 된다.
--
-- 유예 기간을 두고 물리 삭제하는 방식을 택했다(티켓 선택지 1). 소프트 삭제를 쓰는 이유가
-- 복구 가능성이므로 즉시 삭제는 앞뒤가 맞지 않고, 무한 축적도 막아야 한다.
--
-- 그 유예를 재려면 <언제 삭제됐는지>가 필요하다. updated_at 으로 근사할 수는 있지만 삭제 외의
-- 갱신에도 움직이므로 "삭제 후 N일" 의 기준으로 쓸 수 없다. 그래서 전용 컬럼을 둔다.
--
-- 기존 행은 NULL 이다. 이 컬럼이 생기기 전에 삭제된 프로젝트는 삭제 시각을 알 수 없으므로
-- 퍼지 대상에서 제외된다 — 알 수 없는 시점을 임의로 채워 지우는 것보다 남기는 쪽이 안전하다.
ALTER TABLE projects ADD COLUMN deleted_at TIMESTAMP;
